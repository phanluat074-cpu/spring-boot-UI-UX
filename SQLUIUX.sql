go 
use QLHV
go 


-- 1. Tạo bảng DANHMUC (Danh mục)
CREATE TABLE DANHMUC (
    MaDM INT PRIMARY KEY,
    TenDanhMuc NVARCHAR(255),
    IconURL VARCHAR(MAX)
);

-- 2. Tạo bảng BAIHOC (Bài học)
CREATE TABLE BAIHOC (
    MaBH INT PRIMARY KEY,
    TenBH NVARCHAR(255),
    NoiDungBH NVARCHAR(MAX),
    LinkURL VARCHAR(MAX),
    HinhAnh VARCHAR(MAX),
    NgayDang DATETIME,
    MaDM INT,
    CONSTRAINT FK_BAIHOC_DANHMUC FOREIGN KEY (MaDM) REFERENCES DANHMUC(MaDM)
);

-- 3. Tạo bảng INTERACTIVE_LAB (Phòng thí nghiệm tương tác)
CREATE TABLE INTERACTIVE_LAB (
    MaTH INT PRIMARY KEY,
    TenThucHanh NVARCHAR(255),
    MoTaThucHanh NVARCHAR(MAX),
    TrangThaiBanDau NVARCHAR(MAX),
    TrangThaiDung NVARCHAR(MAX),
    GoiY NVARCHAR(MAX),
    MaBH INT,
    CONSTRAINT FK_LAB_BAIHOC FOREIGN KEY (MaBH) REFERENCES BAIHOC(MaBH)
);

-- 4. Tạo bảng TAINGUYEN (Tài nguyên)
CREATE TABLE TAINGUYEN (
    MaTaiNguyen INT PRIMARY KEY,
    TenTaiNguyen NVARCHAR(255),
    LinkURL VARCHAR(MAX),
    DinhDang VARCHAR(50),
    DungLuong VARCHAR(50),
    HinhAnhPreview VARCHAR(MAX),
    MoTa NVARCHAR(MAX),
    MaBH INT,
    CONSTRAINT FK_TAINGUYEN_BAIHOC FOREIGN KEY (MaBH) REFERENCES BAIHOC(MaBH)
);

-- 5. Tạo bảng TRACNGHIEM (Trắc nghiệm)
CREATE TABLE TRACNGHIEM (
    MaTN INT PRIMARY KEY,
    NoiDungCauHoi NVARCHAR(MAX),
    HinhAnh VARCHAR(MAX),
    LoiGiaiThich NVARCHAR(MAX),
    MaBH INT,
    CONSTRAINT FK_TRACNGHIEM_BAIHOC FOREIGN KEY (MaBH) REFERENCES BAIHOC(MaBH)
);

-- 6. Tạo bảng DAPAN (Đáp án)
CREATE TABLE DAPAN (
    MaDA INT PRIMARY KEY,
    NoiDungDapAn NVARCHAR(MAX),
    IsCorrect BIT,
    MaTN INT,
    CONSTRAINT FK_DAPAN_TRACNGHIEM FOREIGN KEY (MaTN) REFERENCES TRACNGHIEM(MaTN)
);